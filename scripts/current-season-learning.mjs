#!/usr/bin/env node
/*
  Incremental 2026/27 learner.
  Unlike historical-training.mjs this does NOT replay five seasons. It reads the
  current-season dataset, finds Gameweeks after CURRENT_SEASON_MODEL.lastLearnedGW,
  and applies one online update per newly completed Gameweek. Running it again
  with no new completed GW is a no-op.
*/
import fs from "node:fs";
const ROOT="https://raw.githubusercontent.com/vaastav/Fantasy-Premier-League/master/data";
const SEASON="2026-27";
const MODEL_FILE="lib/current-season-model.ts";
const KEYS=["form3","form5","p90","xgi90","xg90","xa90","dc90","bonus90","bps90","ict90","threat90","creativity90","influence90","goals90","assists90","saves90","cleanSheetRate","startRate","minutesRate","recentMinutesRate"];
const num=v=>{const n=Number(v);return Number.isFinite(n)?n:0};
const mean=a=>a.length?a.reduce((s,x)=>s+x,0)/a.length:0;
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
function csv(t){const rows=[];let r=[],c="",q=false;for(let i=0;i<t.length;i++){const ch=t[i],nx=t[i+1];if(q){if(ch==='"'&&nx==='"'){c+='"';i++}else if(ch==='"')q=false;else c+=ch}else if(ch==='"')q=true;else if(ch===','){r.push(c);c=""}else if(ch==='\\n'){r.push(c.replace(/\\r$/,""));rows.push(r);r=[];c=""}else c+=ch}if(c||r.length){r.push(c);rows.push(r)}const h=rows.shift()||[];return rows.filter(x=>x.length===h.length).map(x=>Object.fromEntries(h.map((k,i)=>[k,x[i]])));}
async function get(u){const r=await fetch(u);if(!r.ok)throw Error(r.status+" "+u);return r.text()}
function features(history){
 const last3=history.slice(-3),last5=history.slice(-5),mins=Math.max(1,history.reduce((s,x)=>s+x.minutes,0)),n=Math.max(1,history.length);
 const per90=k=>history.reduce((s,x)=>s+num(x[k]),0)/(mins/90);
 return {form3:mean(last3.map(x=>x.points)),form5:mean(last5.map(x=>x.points)),p90:per90("points"),xgi90:per90("xgi"),xg90:per90("xg"),xa90:per90("xa"),dc90:per90("dc"),bonus90:per90("bonus"),bps90:per90("bps"),ict90:per90("ict"),threat90:per90("threat"),creativity90:per90("creativity"),influence90:per90("influence"),goals90:per90("goals"),assists90:per90("assists"),saves90:per90("saves"),cleanSheetRate:mean(history.map(x=>x.clean_sheet)),startRate:history.reduce((s,x)=>s+num(x.starts),0)/n,minutesRate:mins/(90*n),recentMinutesRate:history.slice(-3).reduce((s,x)=>s+x.minutes,0)/(90*Math.max(1,last3.length))};
}
function normalise(rows){
 const stats={};for(const k of KEYS){const a=rows.map(x=>x[k]),m=mean(a),sd=Math.sqrt(mean(a.map(v=>(v-m)**2)))||1;stats[k]=[m,sd]}
 return rows.map(x=>({...x,z:Object.fromEntries(KEYS.map(k=>[k,(x[k]-stats[k][0])/stats[k][1]]))}));
}
function loadModel(){
 const text=fs.readFileSync(MODEL_FILE,"utf8");
 const start=text.indexOf("export const CURRENT_SEASON_MODEL=");
 const end=text.lastIndexOf(" as const;");
 if(start<0||end<0)throw Error("Unable to parse "+MODEL_FILE);
 const json=text.slice(start+"export const CURRENT_SEASON_MODEL=".length,end).trim();
 return JSON.parse(json);
}
function saveModel(m){
 const out=["// Generated by scripts/current-season-learning.mjs.","// Incremental 2026/27 learning state; completed Gameweeks are learned once.","export const CURRENT_SEASON_MODEL="+JSON.stringify(m,null,2)+" as const;",""].join("\\n");
 fs.writeFileSync(MODEL_FILE,out);
}
async function main(){
 const m=loadModel();
 const raw=csv(await get(ROOT+"/"+SEASON+"/gws/merged_gw.csv"));
 const rows=raw.map(r=>({id:num(r.element),gw:num(r.GW||r.round||r.event),points:num(r.total_points),minutes:num(r.minutes),starts:num(r.starts),xg:num(r.expected_goals),xa:num(r.expected_assists),xgi:num(r.expected_goal_involvements),dc:num(r.defensive_contribution),bonus:num(r.bonus),bps:num(r.bps),ict:num(r.ict_index),threat:num(r.threat),creativity:num(r.creativity),influence:num(r.influence),goals:num(r.goals_scored),assists:num(r.assists),saves:num(r.saves),clean_sheet:num(r.clean_sheets)})).filter(r=>r.id&&r.gw);
 const maxCompleted=Math.max(0,...rows.map(r=>r.gw));
 if(maxCompleted<=m.lastLearnedGW){console.log("No new completed Gameweek. Model remains at GW"+m.lastLearnedGW);return;}
 const byId=new Map();
 for(const r of rows){if(!byId.has(r.id))byId.set(r.id,[]);byId.get(r.id).push(r)}
 const lr=0.00002;
 for(let gw=m.lastLearnedGW+1;gw<=maxCompleted;gw++){
  const examples=[];
  for(const [id,hist] of byId){
   const past=hist.filter(x=>x.gw<gw);
   const actual=hist.find(x=>x.gw===gw);
   if(!actual||past.length<1)continue;
   examples.push({...features(past),id,actual:actual.points});
  }
  const norm=normalise(examples);
  for(const p of norm){
   const pred=Number(m.weights.bias||0)+KEYS.reduce((s,k)=>s+Number(m.weights[k]||0)*Number(p.z[k]||0),0);
   const err=clamp((p.actual-pred)/8,-1,1);
   for(const k of KEYS)m.weights[k]=Number(clamp(Number(m.weights[k]||0)+lr*err*Number(p.z[k]||0),-0.9,0.9).toFixed(8));
   m.weights.bias=Number(clamp(Number(m.weights.bias||0)+lr*err,-0.9,0.9).toFixed(8));
  }
  m.lastLearnedGW=gw;
  console.log("Learned GW",gw,"examples",norm.length);
 }
 saveModel(m);
 console.log("CURRENT_SEASON_MODEL",JSON.stringify({season:m.season,lastLearnedGW:m.lastLearnedGW,weights:m.weights},null,2));
}
main().catch(e=>{console.error(e);process.exit(1)});
